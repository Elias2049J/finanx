-- The refresh-token table predates Flyway in some deployments. Own it here so
-- a database migrated from V1 can issue and revoke sessions reproducibly.
CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    family_id VARCHAR(255) NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL,
    revocado_en TIMESTAMPTZ,
    reemplazado_por VARCHAR(255),
    creado_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (id_usuario) REFERENCES public.usuarios(id) ON DELETE CASCADE
);

-- This table existed outside Flyway in earlier installations. Refuse to adopt
-- an incompatible shape instead of silently applying security checks to it.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'refresh_tokens'
          AND column_name = 'id'
          AND is_identity = 'YES'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'id_usuario' AND is_nullable = 'NO'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'token_hash' AND is_nullable = 'NO'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'family_id' AND is_nullable = 'NO'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'expira_en' AND is_nullable = 'NO'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'revocado_en'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'reemplazado_por'
    ) OR NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'refresh_tokens'
          AND column_name = 'creado_en' AND is_nullable = 'NO'
    ) THEN
        RAISE EXCEPTION 'Existing refresh_tokens table has an incompatible column layout; inspect it before applying V9';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.refresh_tokens'::regclass AND contype = 'p'
    ) OR NOT EXISTS (
        SELECT 1
        FROM pg_index i
        WHERE i.indrelid = 'public.refresh_tokens'::regclass
          AND i.indisunique
          AND i.indpred IS NULL
          AND pg_get_indexdef(i.indexrelid) ILIKE '%(token_hash)%'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.refresh_tokens'::regclass
          AND contype = 'f'
          AND confrelid = 'public.usuarios'::regclass
          AND confdeltype = 'c'
    ) THEN
        RAISE EXCEPTION 'Existing refresh_tokens table is missing its primary key, unique token hash or cascading user foreign key';
    END IF;
END
$$;

-- Preserve the indexes used by the existing entity/repository on installations
-- where the table was created before Flyway managed it.
CREATE INDEX IF NOT EXISTS idx_refresh_token_family
    ON public.refresh_tokens (family_id);
CREATE INDEX IF NOT EXISTS idx_refresh_token_usuario
    ON public.refresh_tokens (id_usuario);
CREATE INDEX IF NOT EXISTS idx_refresh_token_expira
    ON public.refresh_tokens (expira_en);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.refresh_tokens
        WHERE revocado_en IS NULL
        GROUP BY family_id
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Cannot enforce one active refresh token per family: duplicate active family_id values exist';
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_refresh_token_active_family
    ON public.refresh_tokens (family_id)
    WHERE revocado_en IS NULL;
