CREATE TABLE public.email_verification_challenges
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(320) NOT NULL,
    purpose         VARCHAR(32) NOT NULL,
    code_hash       VARCHAR(100) NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    last_sent_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_email_verification_email_purpose UNIQUE (email, purpose),
    CONSTRAINT ck_email_verification_failed_attempts CHECK (failed_attempts BETWEEN 0 AND 5),
    CONSTRAINT ck_email_verification_purpose CHECK (purpose IN ('REGISTRATION', 'EXISTING_ACCOUNT'))
);

CREATE INDEX idx_email_verification_expires
    ON public.email_verification_challenges (expires_at);
