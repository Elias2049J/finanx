-- Integracion inicial con Google Play Billing.
-- El modo fake permite probar el flujo completo sin Play Console; el modo
-- real se habilitara cuando exista service account y productos publicados.

ALTER TABLE public.pagos
    DROP CONSTRAINT IF EXISTS pagos_proveedor_check;

ALTER TABLE public.pagos
    ADD CONSTRAINT pagos_proveedor_check
        CHECK (((proveedor)::text = ANY ((ARRAY[
            'MERCADO_PAGO'::character varying,
            'CULQI'::character varying,
            'STRIPE'::character varying,
            'GOOGLE_PLAY'::character varying
        ])::text[])));

ALTER TABLE public.eventos_webhook
    DROP CONSTRAINT IF EXISTS eventos_webhook_proveedor_check;

ALTER TABLE public.eventos_webhook
    ADD CONSTRAINT eventos_webhook_proveedor_check
        CHECK (((proveedor)::text = ANY ((ARRAY[
            'MERCADO_PAGO'::character varying,
            'CULQI'::character varying,
            'STRIPE'::character varying,
            'GOOGLE_PLAY'::character varying
        ])::text[])));

CREATE TABLE public.compras_google_play (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
    id_suscripcion bigint REFERENCES public.suscripciones(id) ON DELETE CASCADE,
    id_pago bigint REFERENCES public.pagos(id) ON DELETE CASCADE,
    token_compra character varying(2048) NOT NULL,
    id_orden character varying(255),
    producto_id character varying(255) NOT NULL,
    plan_base_id character varying(255),
    estado character varying(32) NOT NULL,
    fecha_expiracion timestamp(6) with time zone,
    renovacion_automatica boolean NOT NULL DEFAULT true,
    modo_prueba boolean NOT NULL DEFAULT false,
    fecha_creacion timestamp(6) with time zone,
    fecha_actualizacion timestamp(6) with time zone,
    CONSTRAINT compras_google_play_estado_check
        CHECK (((estado)::text = ANY ((ARRAY[
            'ACTIVE'::character varying,
            'PENDING'::character varying,
            'CANCELED'::character varying,
            'EXPIRED'::character varying,
            'REVOKED'::character varying
        ])::text[]))),
    CONSTRAINT compras_google_play_token_unique UNIQUE (token_compra)
);

CREATE INDEX idx_compras_google_play_usuario
    ON public.compras_google_play (id_usuario);

CREATE INDEX idx_compras_google_play_suscripcion
    ON public.compras_google_play (id_suscripcion);

CREATE INDEX idx_compras_google_play_pago
    ON public.compras_google_play (id_pago);
